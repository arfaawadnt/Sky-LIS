using Platform.SharedKernel.Primitives;

namespace Platform.Domain.Patients;

/// <summary>A document file accepted by <see cref="PatientDocumentFiles.Inspect"/>: the cleaned display name, the extension and the detected content type.</summary>
public sealed record DocumentFile(string FileName, string Extension, string ContentType, long SizeBytes);

/// <summary>
/// The content rules of patient documents (INV-PAT-008): PDF, JPEG or PNG by extension <b>and</b> by the file's
/// signature (magic bytes), 1 byte to 10 MB. The content type is the detected one, never the client's. The client's
/// file name is kept for display only; storage keys are generated by the file store.
/// </summary>
public static class PatientDocumentFiles
{
    public const long MaxSizeBytes = 10L * 1024 * 1024;
    public const int MaxFileNameLength = 255;

    /// <summary>Bytes of the head of a file the signature check needs.</summary>
    public const int HeaderLength = 8;

    private static readonly byte[] PdfSignature = "%PDF-"u8.ToArray();
    private static readonly byte[] JpegSignature = [0xFF, 0xD8, 0xFF];
    private static readonly byte[] PngSignature = [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A];

    private static readonly Dictionary<string, string> ContentTypes = new(StringComparer.Ordinal)
    {
        ["pdf"] = "application/pdf",
        ["jpg"] = "image/jpeg",
        ["jpeg"] = "image/jpeg",
        ["png"] = "image/png",
    };

    public static IReadOnlyCollection<string> AllowedExtensions => ContentTypes.Keys;

    /// <summary>The content type the signature of <paramref name="header"/> announces, or <see langword="null"/>.</summary>
    public static string? DetectContentType(ReadOnlySpan<byte> header)
    {
        if (header.StartsWith(PdfSignature))
        {
            return "application/pdf";
        }

        if (header.StartsWith(PngSignature))
        {
            return "image/png";
        }

        return header.StartsWith(JpegSignature) ? "image/jpeg" : null;
    }

    /// <summary>Validates name, size, extension and signature; returns the accepted file or refuses with PAT-040…044.</summary>
    public static DocumentFile Inspect(string? fileName, long sizeBytes, ReadOnlySpan<byte> header)
    {
        var name = CleanFileName(fileName);
        if (sizeBytes <= 0)
        {
            throw new DomainException(PatientCodes.DocumentEmpty, "The file is empty.", DomainFault.Validation);
        }

        if (sizeBytes > MaxSizeBytes)
        {
            throw new DomainException(PatientCodes.DocumentTooLarge, $"A document may not exceed {MaxSizeBytes / (1024 * 1024)} MB.", DomainFault.Validation);
        }

        var dot = name.LastIndexOf('.');
        var extension = dot < 0 ? string.Empty : name[(dot + 1)..].ToLowerInvariant();
        if (!ContentTypes.TryGetValue(extension, out var expected))
        {
            throw new DomainException(PatientCodes.DocumentTypeNotAllowed, "Only PDF, JPEG or PNG files can be attached.", DomainFault.Validation);
        }

        if (!string.Equals(DetectContentType(header), expected, StringComparison.Ordinal))
        {
            throw new DomainException(PatientCodes.DocumentContentMismatch, "The file content does not match its extension.", DomainFault.Validation);
        }

        return new DocumentFile(name, extension, expected, sizeBytes);
    }

    /// <summary>The last path segment without control or reserved characters, 1–255 characters (PAT-044).</summary>
    public static string CleanFileName(string? fileName)
    {
        var lastSegment = (fileName ?? string.Empty).Replace('\\', '/');
        var slash = lastSegment.LastIndexOf('/');
        if (slash >= 0)
        {
            lastSegment = lastSegment[(slash + 1)..];
        }

        var cleaned = new string(lastSegment.Where(character => !char.IsControl(character) && character is not ('<' or '>' or ':' or '"' or '|' or '?' or '*')).ToArray()).Trim().Trim('.').Trim();
        if (cleaned.Length is < 1 or > MaxFileNameLength)
        {
            throw new DomainException(PatientCodes.DocumentFileNameInvalid, $"The file name must be 1 to {MaxFileNameLength} characters.", DomainFault.Validation);
        }

        return cleaned;
    }
}
