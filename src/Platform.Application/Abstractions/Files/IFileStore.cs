namespace Platform.Application.Abstractions.Files;

/// <summary>What the store wrote: the opaque key to keep on the owning row, the byte count and the SHA-256 (lower-case hex).</summary>
public sealed record StoredFile(string StorageKey, long SizeBytes, string Sha256)
{
    /// <summary>The file id: the last segment of the key (a GUID v7 the store generated).</summary>
    public Guid FileId => FileKeys.FileIdOf(StorageKey);
}

/// <summary>
/// The layout of a storage key, <c>&lt;tenant&gt;/&lt;area&gt;/&lt;owner&gt;/&lt;file id&gt;</c> (GUIDs as 32 hex digits). An
/// owner that keeps only a file id (a report template's logo, intake LIS-INT-CTB-001 A10) composes its key back with the
/// <b>current</b> tenant, so a file id never opens another tenant's content.
/// </summary>
public static class FileKeys
{
    /// <summary>The key of <paramref name="fileId"/> below <paramref name="area"/>/<paramref name="ownerId"/> of <paramref name="tenantId"/>.</summary>
    public static string Compose(Guid tenantId, string area, Guid ownerId, Guid fileId) => $"{tenantId:N}/{area}/{ownerId:N}/{fileId:N}";

    /// <summary>The file id of a key written by the store.</summary>
    public static Guid FileIdOf(string storageKey)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(storageKey);
        var slash = storageKey.LastIndexOf('/');
        return Guid.ParseExact(storageKey[(slash + 1)..], "N");
    }
}

/// <summary>
/// Shared binary storage for attachments of every module (patient documents first). Keys are generated by the store
/// as <c>&lt;tenant&gt;/&lt;area&gt;/&lt;owner&gt;/&lt;guid v7&gt;</c> from the <b>current tenant</b> (never from a request),
/// so a client file name never reaches a path and a key of another tenant is refused on read. The store keeps bytes
/// only; the owning aggregate keeps the metadata (name, content type, hash, who, when). Business deletion does not
/// exist (BR-15): <see cref="DeleteAsync"/> is the compensation of a commit that failed after <see cref="SaveAsync"/>.
/// </summary>
public interface IFileStore
{
    /// <summary>
    /// Writes <paramref name="content"/> under a new key below <paramref name="area"/>/<paramref name="ownerId"/> of the
    /// current tenant. <paramref name="area"/> is a lower-case module word (<c>patients</c>, <c>results</c> …). Throws
    /// <see cref="InvalidOperationException"/> when no tenant is resolved and <see cref="IOException"/> when more than
    /// <paramref name="maxBytes"/> bytes arrive (nothing is left behind).
    /// </summary>
    Task<StoredFile> SaveAsync(string area, Guid ownerId, Stream content, long maxBytes, CancellationToken cancellationToken);

    /// <summary>Opens the content for reading, or <see langword="null"/> when the key is unknown, malformed or belongs to another tenant.</summary>
    Task<Stream?> OpenReadAsync(string storageKey, CancellationToken cancellationToken);

    /// <summary>Removes the content of a key of the current tenant (compensation only); a missing file is not an error.</summary>
    Task DeleteAsync(string storageKey, CancellationToken cancellationToken);

    /// <summary>
    /// Copies the content of <paramref name="sourceKey"/> — a key of <b>any</b> tenant — to a new key below
    /// <paramref name="area"/>/<paramref name="ownerId"/> of the current tenant. Only inside an elevated scope (the
    /// provisioning copies the platform catalogue's files to a new laboratory, BR-25); throws
    /// <see cref="InvalidOperationException"/> otherwise. Returns <see langword="null"/> when the source key is malformed
    /// or its content is missing; <see cref="IOException"/> when it holds more than <paramref name="maxBytes"/> bytes.
    /// </summary>
    Task<StoredFile?> CopyAsync(string sourceKey, string area, Guid ownerId, long maxBytes, CancellationToken cancellationToken);
}
